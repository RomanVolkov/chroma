import type { SchemeData } from '../../worker/types';

export interface ThemeExporter {
  id: string;
  name: string;
  filename: (slug: string) => string;
  category: 'Editor' | 'Terminal' | 'CLI' | 'Desktop' | 'App';
  generate: (scheme: SchemeData) => string;
}

function getSlug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'theme';
}

function hexNoHash(hex: string): string {
  return hex.replace('#', '');
}

