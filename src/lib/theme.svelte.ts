export function generateDotfilesToml(s: SchemeData): string {
  const c = s.colors;
  const ansi = s.ansi?.colors || [];
  const normal = ansi.slice(0, 8);
  const bright = ansi.slice(8, 16);
  const batTheme = s.tools?.bat || 'base16';

  let toolsBlock = `\n[tools]\nbat = "${batTheme}"\n`;
  if (s.tools) {
    for (const [k, v] of Object.entries(s.tools)) {
      if (k !== 'bat') {
        toolsBlock += `${k} = "${v}"\n`;
      }
    }
  }

  return `# ${s.name} — Generated by Chroma
name = "${s.name}"
variant = "${s.variant}"

[colors]
bg            = "${c.bg}"
bg_alt        = "${c.bg_alt}"
bg_deep       = "${c.bg_deep}"
fg            = "${c.fg}"
fg_dim        = "${c.fg_dim}"
fg_muted      = "${c.fg_muted}"
surface       = "${c.surface}"
surface_hi    = "${c.surface_hi}"
border        = "${c.border}"
overlay       = "${c.overlay}"
cursor        = "${c.cursor}"
selection_bg  = "${c.selection_bg}"
selection_fg  = "${c.selection_fg}"
accent        = "${c.accent}"
accent_alt    = "${c.accent_alt}"
accent_info   = "${c.accent_info}"
warn          = "${c.warn}"
blue          = "${c.blue}"

[ansi]
colors = [
  ${normal.map((x) => `"${x}"`).join(', ')},
  ${bright.map((x) => `"${x}"`).join(', ')},
]
${toolsBlock}`;
}

export class ThemeStore {
  imageUrl = $state<string | null>(null);
  imageWidth = $state<number>(0);
  imageHeight = $state<number>(0);
  isAnalyzing = $state<boolean>(false);
  error = $state<string | null>(null);
  statusMessage = $state<string | null>(null);
  lastImportedFormat = $state<string | null>(null);
  lastImportedName = $state<string | null>(null);

  swatches = $state<Swatch[]>([]);
  scheme = $state<SchemeData>(JSON.parse(JSON.stringify(DEFAULT_SCHEME)));
  toml = $state<string>(generateDotfilesToml(DEFAULT_SCHEME));

  activeSlot = $state<ActiveSlot | null>(null);
  hoveredSlot = $state<ActiveSlot | null>(null);

  // Cached downscaled pixels for instant re-clustering on variant switch
  private cachedPixels: Uint8Array | null = null;

  async loadFile(file: File) {
    this.isAnalyzing = true;
    this.error = null;
    this.lastImportedFormat = null;
    this.lastImportedName = null;

    try {
      if (this.imageUrl) {
        URL.revokeObjectURL(this.imageUrl);
      }
      this.imageUrl = URL.createObjectURL(file);

      // Derive theme name from filename
      const baseName = file.name.replace(/\.[^/.]+$/, '').replace(/[-_]/g, ' ');
      this.scheme.name = baseName.charAt(0).toUpperCase() + baseName.slice(1);

      // Load image into HTMLImageElement to downscale to ~384px for fast k-means
      const img = new Image();
      img.src = this.imageUrl;
      await new Promise((resolve, reject) => {
        img.onload = resolve;
        img.onerror = reject;
      });

      this.imageWidth = img.naturalWidth;
      this.imageHeight = img.naturalHeight;

      // Downsample to max 384x384 for clustering
      const maxDim = 384;
      let targetW = img.naturalWidth;
      let targetH = img.naturalHeight;
      if (targetW > maxDim || targetH > maxDim) {
        if (targetW > targetH) {
          targetH = Math.round((targetH * maxDim) / targetW);
          targetW = maxDim;
        } else {
          targetW = Math.round((targetW * maxDim) / targetH);
          targetH = maxDim;
        }
      }

      const canvas = document.createElement('canvas');
      canvas.width = targetW;
      canvas.height = targetH;
      const ctx = canvas.getContext('2d', { willReadFrequently: true });
      if (!ctx) throw new Error('Failed to create canvas context');

      ctx.drawImage(img, 0, 0, targetW, targetH);
      const imgData = ctx.getImageData(0, 0, targetW, targetH);
      this.cachedPixels = new Uint8Array(imgData.data.buffer);

      // Run extraction in Go WebAssembly worker
      const result: ExtractResult = await extractPalette(
        this.cachedPixels.slice(),
        this.scheme.variant,
        16
      );

      this.swatches = [...result.swatches];
      const validatedColors = autoFixContrast(result.scheme.colors, this.scheme.variant);
      this.scheme = {
        name: this.scheme.name,
        variant: this.scheme.variant,
        colors: validatedColors,
        ansi: { colors: [...result.scheme.ansi.colors] },
        tools: { ...this.scheme.tools },
      };
      this.updateToml();
    } catch (err: any) {
      console.error('Error extracting palette from image:', err);
      this.error = err?.message || 'Failed to process image';
    } finally {
      this.isAnalyzing = false;
    }
  }

  async setVariant(variant: 'dark' | 'light') {
    if (this.scheme.variant === variant && !this.cachedPixels) return;

    if (this.cachedPixels) {
      this.scheme.variant = variant;
      this.isAnalyzing = true;
      try {
        const result = await extractPalette(this.cachedPixels.slice(), variant, 16);
        this.swatches = [...result.swatches];
        const validatedColors = autoFixContrast(result.scheme.colors, variant);
        this.scheme = {
          name: this.scheme.name,
          variant: this.scheme.variant,
          colors: validatedColors,
          ansi: { colors: [...result.scheme.ansi.colors] },
          tools: { ...this.scheme.tools },
        };
        this.updateToml();
      } catch (err: any) {
        console.error('Error updating variant:', err);
        this.error = err?.message || 'Failed to update variant';
      } finally {
        this.isAnalyzing = false;
      }
    } else {
      // No image pixels present: perform intelligent mathematical dark <-> light conversion
      this.scheme = convertThemeVariant(this.scheme, variant);

      // Also update swatches so palette strip reflects the new variant
      const rawColors = [
        this.scheme.colors.bg,
        this.scheme.colors.bg_alt,
        this.scheme.colors.surface,
        this.scheme.colors.border,
        this.scheme.colors.fg_muted,
        this.scheme.colors.fg_dim,
        this.scheme.colors.fg,
        this.scheme.colors.accent,
        this.scheme.colors.accent_alt,
        this.scheme.colors.accent_info,
        this.scheme.colors.warn,
        this.scheme.colors.blue,
        ...this.scheme.ansi.colors,
      ].filter(Boolean);

      const uniqueColors = Array.from(new Set(rawColors.map((c) => c.toLowerCase())));
      this.swatches = uniqueColors.map((hex) => ({
        hex,
        role: 'variant',
        count: 100,
        proportion: 1 / uniqueColors.length,
      }));

      this.updateToml();
    }
  }

  async distributePalette() {
    if (!this.cachedPixels) return;
    this.isAnalyzing = true;
    try {
      const result = await extractPalette(this.cachedPixels.slice(), this.scheme.variant, 16);
      this.swatches = [...result.swatches];
      const validatedColors = autoFixContrast(result.scheme.colors, this.scheme.variant);
      this.scheme = {
        name: this.scheme.name,
        variant: this.scheme.variant,
        colors: validatedColors,
        ansi: { colors: [...result.scheme.ansi.colors] },
        tools: { ...this.scheme.tools },
      };
      this.updateToml();
    } catch (err: any) {
      console.error('Error distributing palette:', err);
      this.error = err?.message || 'Failed to distribute palette';
    } finally {
      this.isAnalyzing = false;
    }
  }

  setActiveSlot(slot: ActiveSlot | null) {
    this.activeSlot = slot;
  }

  setHoveredSlot(slot: ActiveSlot | null) {
    this.hoveredSlot = slot;
  }

  async assignColor(hex: string) {
    if (!this.activeSlot) return;

    if (this.activeSlot.type === 'base') {
      const key = this.activeSlot.key as keyof SchemeColors;
      this.scheme.colors[key] = hex;
    } else if (this.activeSlot.type === 'ansi') {
      const idx = this.activeSlot.key as number;
      this.scheme.ansi.colors[idx] = hex;
    }

    await this.updateToml();
  }

  async importTheme(file: File): Promise<ImportResult> {
    this.error = null;
    this.statusMessage = null;

    try {
      const text = await file.text();
      const result = importThemeFile(text, file.name);

      if (!result.success || result.confidence < 90) {
        const confText = result.confidence > 0 ? ` (${result.confidence}% confidence < 90% required)` : '';
        const msg = result.error || `Import dropped: confidence too low${confText}.`;
        this.error = msg;
        return result;
      }

      if (result.scheme) {
        // Drop selected image so UI represents the imported theme
        if (this.imageUrl) {
          URL.revokeObjectURL(this.imageUrl);
          this.imageUrl = null;
        }
        this.cachedPixels = null;
        this.imageWidth = 0;
        this.imageHeight = 0;
        this.lastImportedFormat = result.formatName;
        this.lastImportedName = file.name;

        this.scheme = {
          name: result.scheme.name || this.scheme.name,
          variant: result.scheme.variant || this.scheme.variant,
          colors: { ...result.scheme.colors },
          ansi: { colors: [...result.scheme.ansi.colors] },
          tools: { ...this.scheme.tools },
        };

        // Create swatches for palette bar from unique imported theme colors
        const rawColors = [
          result.scheme.colors.bg,
          result.scheme.colors.bg_alt,
          result.scheme.colors.surface,
          result.scheme.colors.border,
          result.scheme.colors.fg_muted,
          result.scheme.colors.fg_dim,
          result.scheme.colors.fg,
          result.scheme.colors.accent,
          result.scheme.colors.accent_alt,
          result.scheme.colors.accent_info,
          result.scheme.colors.warn,
          result.scheme.colors.blue,
          ...result.scheme.ansi.colors,
        ].filter(Boolean);

        const uniqueColors = Array.from(new Set(rawColors.map((c) => c.toLowerCase())));
        this.swatches = uniqueColors.map((hex) => ({
          hex,
          role: 'imported',
          count: 100,
          proportion: 1 / uniqueColors.length,
        }));

        await this.updateToml();
        this.statusMessage = `Successfully imported ${result.formatName} (${result.confidence}% confidence)`;
        setTimeout(() => {
          if (this.statusMessage?.startsWith('Successfully imported')) {
            this.statusMessage = null;
          }
        }, 4000);
      }

      return result;
    } catch (err: any) {
      console.error('Failed to import file:', err);
      this.error = `Failed to read file: ${err?.message || err}`;
      return {
        success: false,
        confidence: 0,
        formatName: 'Error',
        error: err?.message,
      };
    }
  }

  updateToml() {
    this.toml = generateDotfilesToml(this.scheme);
  }
}

export const theme = new ThemeStore();
