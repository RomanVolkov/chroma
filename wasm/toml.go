package main

import (
	"fmt"
	"strings"
)

// SerializeTOML formats a Scheme struct into the exact TOML format expected by ~/.dotfiles.
func SerializeTOML(s Scheme) string {
	var b strings.Builder

	// Header comment and top-level fields
	b.WriteString(fmt.Sprintf("# %s — Generated by Chroma\n", s.Name))
	b.WriteString(fmt.Sprintf("name = %q\n", s.Name))
	b.WriteString(fmt.Sprintf("variant = %q\n\n", s.Variant))

	// [colors] section
	b.WriteString("[colors]\n")
	writeColorField(&b, "bg", s.Colors.Bg)
	writeColorField(&b, "bg_alt", s.Colors.BgAlt)
	writeColorField(&b, "bg_deep", s.Colors.BgDeep)
	writeColorField(&b, "fg", s.Colors.Fg)
	writeColorField(&b, "fg_dim", s.Colors.FgDim)
	writeColorField(&b, "fg_muted", s.Colors.FgMuted)
	writeColorField(&b, "surface", s.Colors.Surface)
	writeColorField(&b, "surface_hi", s.Colors.SurfaceHi)
	writeColorField(&b, "border", s.Colors.Border)
	writeColorField(&b, "overlay", s.Colors.Overlay)
	writeColorField(&b, "cursor", s.Colors.Cursor)
	writeColorField(&b, "selection_bg", s.Colors.SelectionBg)
	writeColorField(&b, "selection_fg", s.Colors.SelectionFg)
	writeColorField(&b, "accent", s.Colors.Accent)
	writeColorField(&b, "accent_alt", s.Colors.AccentAlt)
	writeColorField(&b, "accent_info", s.Colors.AccentInfo)
	writeColorField(&b, "warn", s.Colors.Warn)
	writeColorField(&b, "blue", s.Colors.Blue)
	b.WriteString("\n")

	// [ansi] section (split into normal 0-7 and bright 8-15)
	b.WriteString("[ansi]\ncolors = [\n")
	b.WriteString("  ")
	for i := 0; i < 8; i++ {
		b.WriteString(fmt.Sprintf("%q, ", s.ANSI.Colors[i]))
	}
	b.WriteString("\n  ")
	for i := 8; i < 16; i++ {
		b.WriteString(fmt.Sprintf("%q", s.ANSI.Colors[i]))
		if i < 15 {
			b.WriteString(", ")
		}
	}
	b.WriteString(",\n]\n")

	// [tools] section if present
	if len(s.Tools) > 0 {
		b.WriteString("\n[tools]\n")
		for k, v := range s.Tools {
			b.WriteString(fmt.Sprintf("%s = %q\n", k, v))
		}
	}

	return b.String()
}

func writeColorField(b *strings.Builder, key, val string) {
	// Pad key to 13 characters for clean tabular alignment
	padding := 13 - len(key)
	if padding < 1 {
		padding = 1
	}
	b.WriteString(fmt.Sprintf("%s%s = %q\n", key, strings.Repeat(" ", padding), val))
}
